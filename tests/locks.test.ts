test('Pythonの版の順序（PEP 440）と、PyPIのアドバイザリの修正版', () => {
  const sorted = ['1.0.post1', '1.0', '1.0rc1', '1.0.dev1', '1.0a2', '1.0b1', '0.9', '1.0.1', '1!0.1'].sort((a, b) => compareVersions('PyPI', a, b));
  assert.deepEqual(sorted, ['0.9', '1.0.dev1', '1.0a2', '1.0b1', '1.0rc1', '1.0', '1.0.post1', '1.0.1', '1!0.1']);
  assert.ok(compareVersions('PyPI', '2.10', '2.9') > 0);
  assert.ok(compareVersions('Packagist', '5.4.0.1', '5.4.0') > 0, 'Composer versions may have four parts');
  const record: OsvRecord = { id: 'GHSA-p', affected: [{ package: { ecosystem: 'PyPI', name: 'Django' }, ranges: [{ type: 'ECOSYSTEM', events: [{ introduced: '4.2' }, { fixed: '4.2.2' }, { introduced: '5.0a1' }, { fixed: '5.0.1' }] }] }] };
  assert.equal(fixedVersion(record, 'django', '4.2.1', 'PyPI'), '4.2.2');
  assert.equal(fixedVersion(record, 'django', '5.0rc1', 'PyPI'), '5.0.1');
  assert.equal(fixedVersion(record, 'django', '4.2.1'), null, 'an npm package of the same name is not matched');
});

test('API: Composer・Python・Yarn の依存を ecosystem 付きで照会し、対応キュー・検索に出す', async () => {
  await folder(async (root, put) => {
    await put('site/composer.json', json({ require: { 'guzzlehttp/guzzle': '^7.0' } }));
    await put('site/composer.lock', json({ packages: [{ name: 'guzzlehttp/guzzle', version: '7.4.0', 'notification-url': 'https://packagist.org/downloads/' },
      { name: 'acme/vcs', version: '1.0.0', source: { type: 'git', url: 'git@github.com:acme/vcs.git' } }], 'packages-dev': [] }));
    await put('site/requirements.txt', 'Django==4.2.1\nrequests\n');
    await put('site/package.json', json({ dependencies: { lodash: '^4.17.15' } }));
    await put('site/yarn.lock', `# yarn lockfile v1\n\nlodash@^4.17.15:\n  version "4.17.15"\n  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.15.tgz#4c3e"\n`);
    const { Store } = await import('../server/store.js');
    const { createApi } = await import('../server/api.js');
    const { fixtureClient } = await import('../server/osv.js');
    const advisory = (id: string, ecosystem: string, name: string, events: Record<string, string>[]) => ({ id, summary: `${name} の問題`, aliases: [],
      affected: [{ package: { ecosystem, name }, ranges: [{ type: 'ECOSYSTEM', events }] }], database_specific: { severity: 'HIGH' } });
    const fixture = fixtureClient({
      'Packagist:guzzlehttp/guzzle@7.4.0': [advisory('GHSA-guzzle', 'Packagist', 'guzzlehttp/guzzle', [{ introduced: '7.0.0' }, { fixed: '7.4.5' }])],
      'PyPI:django@4.2.1': [advisory('GHSA-django', 'PyPI', 'Django', [{ introduced: '4.2' }, { fixed: '4.2.2' }])],
    });
    const sent: string[] = [];
    const store = new Store(':memory:');
    const api = createApi(store, 4310, undefined, undefined, { osv: { async queryBatch(q) { sent.push(...q.map(x => `${x.ecosystem}:${x.name}@${x.version}`)); return fixture.queryBatch(q); }, vulnerability: fixture.vulnerability } });
    let token = '';
    const call = async (path: string, body?: unknown) => {
      const response = await api.request(`http://127.0.0.1:4310/api${path}`, { method: body === undefined ? 'GET' : 'POST',
        headers: { host: '127.0.0.1:4310', 'x-owndapp-client': 'web', 'x-owndapp-token': token, 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      const data = await response.json() as any; if (path === '/session') token = data.token; return { response, data };
    };
    try {
      await call('/session');
      const { projectIds: [id] } = store.import('eco', [{ technologies: [], components: [], evidence: [], fingerprint: 'x', registered: false, id: 'site', name: 'site', path: join(root, 'site') }]);
      assert.deepEqual((await call('/dependencies/read', { ids: [id] })).data.results.map((r: any) => r.status), ['complete']);
      const preview = (await call('/vulnerabilities/preview', { ids: [id] })).data;
      assert.deepEqual([preview.packageVersions, preview.byEcosystem, preview.notSent], [3, { npm: 1, Packagist: 1, PyPI: 1 }, { git: 1, 'no-version': 1 }]);
      assert.equal(sent.length, 0, 'the preview sends nothing');
      let job = (await call('/vulnerabilities/check', { ids: [id] })).data.job;
      for (let i = 0; i < 500 && job.status === 'running'; i++) { await new Promise(r => setTimeout(r, 2)); job = (await call('/vulnerabilities/job')).data.job; }
      assert.equal(job.status, 'done');
      assert.deepEqual(sent.sort(), ['Packagist:guzzlehttp/guzzle@7.4.0', 'PyPI:django@4.2.1', 'npm:lodash@4.17.15']);
      const check = (await call(`/projects/${id}/vulnerabilities`)).data.check;
      assert.deepEqual(check.findings.map((f: any) => [f.dependency.ecosystem, f.dependency.name, f.advisories[0].fixed]).sort(),
        [['Packagist', 'guzzlehttp/guzzle', '7.4.5'], ['PyPI', 'django', '4.2.2']]);
      const queue = (await call('/queue')).data;
      assert.deepEqual(queue.items.map((i: any) => i.dependencies[0].ecosystem).sort(), ['Packagist', 'PyPI'], 'the queue keeps the ecosystem');
      // Python names match in their normalized form; one name may exist in several ecosystems.
      assert.equal((await call('/dependencies/search?name=DJANGO')).data.matches.length, 1);
      const packages = (await call('/dependencies/packages')).data.packages;
      assert.deepEqual(packages.map((p: any) => `${p.ecosystem}:${p.name}`).sort(), ['Packagist:acme/vcs', 'Packagist:guzzlehttp/guzzle', 'PyPI:django', 'PyPI:requests', 'npm:lodash']);
    } finally { store.close(); }
  });
});
